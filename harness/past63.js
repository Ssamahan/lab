/* v6.9.63 — a leave block can be charged to a past fiscal year, and a month that
   was regenerated by mistake can be put back from its own history:
     · the plan book's "Charged to fiscal year" is a choice, not a caption — it
       defaults to the year the dates fall in and lists the earlier years, so a
       block taken this November can be charged to the FY 2025/2026 days it is
       spending;
     · the year the dates fall in is still read off the dates and cannot be typed;
     · the form says out loud what the chosen year can carry, and warns when the
       block is over it or overlaps a block already on the books;
     · every regeneration is archived, and the history is now a table with a
       Restore button, so a month lost by mistake is one press away. */
const {boot,ok,done}=require('./env');
const tick=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const {w,errors,go}=await boot('#/leave');
  const S=w.LS.store, U=w.LSU, doc=w.document, db=()=>S.db();
  const click=el=>{ if(el) el.click(); };
  const fire=(el,type)=>{ el.dispatchEvent(new w.Event(type,{bubbles:true})); };

  /* ── 1 · the year is a choice ──────────────────────────────────────── */
  await go('#/leave'); await tick(350);
  click(doc.querySelector('[data-newplan]')); await tick(350);
  const charge=doc.querySelector('#plCharge');
  ok(!!charge,'the plan form asks which fiscal year the block is charged to');
  ok(!charge.disabled,'and the field is a choice, not a caption');
  const years=[...charge.options].map(o=>o.value);
  ok(years.indexOf('2025/2026')>=0,'FY 2025/2026 is offered ('+years.join(', ')+')');
  ok(years.indexOf('2026/2027')>=0,'beside the year in force');
  const taken=doc.querySelector('#plTaken');
  ok(!!taken&&taken.readOnly,'the year the dates fall in is still read, never typed');
  ok(/^FY \d{4}\/\d{4}$/.test(taken.value),'and it reads a fiscal year ('+taken.value+')');

  /* ── 2 · a November block charged back to FY 2025/2026 ─────────────── */
  const staffSel=doc.querySelector('#plStaff');
  staffSel.value='s1'; fire(staffSel,'change'); await tick(120);
  const from=doc.querySelector('#plFrom');
  from.value='2027-01-05'; fire(from,'change'); await tick(150);
  ok(doc.querySelector('#plTaken').value==='FY 2026/2027','January 2027 falls in FY 2026/2027 ('+doc.querySelector('#plTaken').value+')');
  ok(charge.value==='2026/2027','and the charge defaults to that same year');
  const days=doc.querySelector('#plDays');
  days.value='20'; fire(days,'input'); await tick(150);
  ok(doc.querySelector('#plTo').value==='2027-01-24','twenty days from 5 January ends on the 24th');
  charge.value='2025/2026'; fire(charge,'change'); await tick(150);
  const summary=doc.querySelector('#plSummary').textContent.replace(/\\s+/g,' ').trim();
  ok(/charged to FY 2025\/2026/.test(summary),'the summary says which year the days come out of ('+summary.slice(0,110)+')');
  ok(/over what that year can carry/.test(summary),'and warns that the year cannot carry another twenty days');
  click(doc.querySelector('[data-save]')); await tick(400);

  const rec=S.leaves().find(l=>l.staffId==='s1'&&l.from==='2027-01-05'&&l.id!=='l18');
  ok(!!rec,'the block is saved');
  ok(rec.fy==='2026/2027','its own year is the year the dates fall in ('+rec.fy+')');
  ok(rec.chargedFy==='2025/2026','and it is charged to the year it was told to ('+rec.chargedFy+')');
  ok(S.leaveChargedFy(rec)==='2025/2026','the register answers with that year');

  /* ── 3 · it appears in both books, each for its own reason ─────────── */
  const prev=S.leaveBook(S.staffById('s1'),'2025/2026');
  ok(prev.rows.some(l=>l.id===rec.id),'the FY 2025/2026 book lists the block');
  ok(prev.charged>=50,'and its days are charged to that year ('+prev.charged+')');
  ok(prev.over>0,'the year is shown as over its entitlement, not hidden');
  const now=S.leaveBook(S.staffById('s1'),'2026/2027');
  ok((now.chargedElsewhere||[]).some(c=>c.id===rec.id),'the year in force names the year it was charged to');
  ok(!now.chargedRows.some(l=>l.id===rec.id),'without charging itself for it');

  /* the book on screen reads the same */
  const fyBtn=[...doc.querySelectorAll('[data-fy]')].filter(b=>/2025\/2026/.test(b.textContent))[0];
  ok(!!fyBtn,'the book can be switched to FY 2025/2026');
  click(fyBtn); await tick(400);
  const kelRow=[...doc.querySelectorAll('table tbody tr')].find(tr=>/Kelvin SAMAHANI/.test(tr.textContent));
  ok(!!kelRow&&/5 Jan/.test(kelRow.textContent),'his row carries the January block in that year');

  /* ── 4 · editing keeps the year it was charged to ──────────────────── */
  const chip=kelRow.querySelector('[data-editplan="'+rec.id+'"]');
  ok(!!chip,'the block can be opened from the row');
  click(chip); await tick(350);
  ok(doc.querySelector('#plCharge')&&doc.querySelector('#plCharge').value==='2025/2026',
     'the editor opens on the year it was charged to');
  ok(doc.querySelector('#plFrom').value==='2027-01-05','with its own dates');
  click(doc.querySelector('[data-close]')); await tick(250);

  /* ── 5 · a regenerated month is one press from being put back ──────── */
  await go('#/roster'); await tick(400);
  click(doc.querySelector('[data-view="grid"]')); await tick(400);
  const before=S.planForMonth(U.monthKey());
  ok(!!before,'the month in force has a plan ('+U.monthKey()+')');
  const fingerprint=JSON.stringify(before.staff.map(r=>r.codes.join('')));
  click(doc.querySelector('[data-generate]')); await tick(350);
  const gen=[...doc.querySelectorAll('.modal button, .confirm button')].find(b=>/Generate draft|Archive & regenerate/i.test(b.textContent));
  ok(!!gen,'regenerating asks first');
  click(gen); await tick(500);
  const versionsNow=()=>((db().workingPlans[U.monthKey()]||{}).versions||[]);
  ok(versionsNow().length>=1,'the grid it replaced is archived ('+versionsNow().length+')');
  const card=[...doc.querySelectorAll('#app .card')].find(c=>/Plan history/.test(c.textContent));
  ok(!!card,'the working plan shows the history of the month');
  const buttons=[...card.querySelectorAll('[data-restore]')];
  ok(buttons.length===versionsNow().length,'one Restore per archived version ('+buttons.length+')');

  /* the version just archived is the grid that was in force */
  const idx=versionsNow().findIndex(v=>JSON.stringify(v.staff.map(r=>r.codes.join('')))===fingerprint);
  ok(idx>=0,'the archived copy is the grid that was in force');
  const btn=[...card.querySelectorAll('[data-restore]')].find(b=>+b.dataset.restore===idx);
  click(btn); await tick(350);
  const yes=[...doc.querySelectorAll('.modal button, .confirm button')].find(b=>/Restore version/i.test(b.textContent));
  ok(!!yes,'restoring asks first');
  click(yes); await tick(600);
  const after=S.planForMonth(U.monthKey());
  ok(JSON.stringify(after.staff.map(r=>r.codes.join('')))===fingerprint,'the grid comes back cell for cell');
  ok(versionsNow().some(v=>JSON.stringify(v.staff.map(r=>r.codes.join('')))!==fingerprint),
     'and the draft it replaced is kept in the history');

  ok(errors.length===0,'no console errors during the run');
  done('past63');
})();
