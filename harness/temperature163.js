const {boot,ok,done}=require('./env');
(async()=>{
  const {w,errors}=await boot('#/roster');
  const S=w.LS.store, U=w.LSU, doc=w.document;
  doc.querySelector('[data-view="week"]').click();
  await new Promise(r=>setTimeout(r,350));
  const rows=[...doc.querySelectorAll('table.cal tfoot tr')];
  const ti=rows.findIndex(row=>row.textContent.includes('Temperature monitoring'));
  const ni=rows.findIndex(row=>row.textContent.includes('Night'));
  ok(ti>=0 && ti===ni-1,'temperature monitoring immediately precedes night duty');
  const dates=S.weekDates(S.weekStart(U.todayISO()));
  const people=['Kelvin SAMAHANI','Beatrice NGEZEKURE','Patrick Test','Claudine Test'];
  const originalDuty=S.onDuty, originalHoliday=S.db().holidays;
  S.db().holidays=[];
  const names={}; dates.forEach((d,i)=>names[d]=i<5?[people[0],people[1],people[2],people[3]]:[people[1]]);
  S.onDuty=d=>(names[d]||[]).map(name=>({kind:'day',staff:{name}}));
  const start=S.weekStart(U.todayISO());
  S.db().unitRosters[start]=S.db().unitRosters[start]||{weekStart:start,assignments:{}};
  const assignments=S.db().unitRosters[start].assignments;
  dates.forEach(d=>{ assignments[d]=assignments[d]||{}; assignments[d].Parasitology=people[3]; });
  const render=()=>{w.LS.modules.roster.render(doc.querySelector('#roBody').parentElement,{tab:'week'}); return [...doc.querySelector('[data-temperature-row]').querySelectorAll('td')].slice(1).map(x=>x.textContent.trim());};
  let cells=render();
  ok(cells.slice(0,5).every(x=>x.includes('Claudine')),'eligible full-week parasitology staff member covers Monday to Friday',cells.join('|'));
  ok(cells.slice(5).every(x=>x.includes('Beatrice')),'weekend day duty monitors temperature',cells.join('|'));
  dates.slice(0,5).forEach((d,i)=>{ names[d]=i===0?[people[0],people[1],people[2],people[3]]:i===1?[people[0],people[1]]:[people[0],people[1],people[2]]; });
  cells=render();
  ok(cells[0].includes('Claudine')&&cells[1].includes('Kelvin')&&cells[2].includes('Patrick'),'without full-week cover, prefer parasitology, then Kelvin when only Kelvin and Beatrice are on duty',cells.join('|'));
  names[dates[0]]=[people[1]]; cells=render();
  ok(cells[0].includes('Beatrice')&&!cells[0].includes('Kelvin'),'assigns the only available person, not absent Kelvin',cells[0]);
  S.onDuty=originalDuty; S.db().holidays=originalHoliday;
  const svg=w.LS.sheets.weeklySVG({weekStart:start,dates,services:[],alloc:{},night:{},temperature:{[dates[0]]:'Patrick Test'}});
  ok(svg.includes('Temperature monitoring')&&svg.indexOf('Temperature monitoring')<svg.indexOf('Night Shift')&&svg.includes('Patrick'),'printed weekly sheet includes the monitor above night');
  ok(!errors.length,'no unexpected runtime errors',errors.join(' | '));
  done('temperature163');
})().catch(e=>{console.error(e);process.exit(1);});
