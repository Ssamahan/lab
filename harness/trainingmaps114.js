const {boot,ok,done}=require('./env');
const wait=ms=>new Promise(r=>setTimeout(r,ms||250));
const click=e=>e.dispatchEvent(new e.ownerDocument.defaultView.MouseEvent('click',{bubbles:true,cancelable:true}));
(async()=>{
 const {w,go,errors}=await boot('#/training'); const d=w.document, S=w.LS.store;
 await go('#/training'); await wait();
 click(d.querySelector('[data-schedule]')); await wait();
 const field=(sel,value)=>{d.querySelector(sel).value=value;};
 ok(!!d.querySelector('#trFacilityName'),'training offers host facility');
 field('#trTitle','Map integration test'); field('#trLoc','Musanze'); field('#trFacilityType','Hotel'); field('#trFacilityName','Example Hotel & Hall');
 let opened=''; w.open=u=>{opened=u;}; click(d.querySelector('[data-find-facility]'));
 ok(opened.includes('google.com/maps/search/')&&decodeURIComponent(opened).includes('Example Hotel & Hall Musanze'),'search encodes name and locality');
 click(d.querySelector('[data-save]')); await wait(500);
 let tr=S.db().trainings.find(x=>x.title==='Map integration test');
 ok(!!tr&&tr.location==='Musanze'&&tr.facilityType==='Hotel'&&tr.facilityName==='Example Hotel & Hall','facility saved separately without replacing location');
 await go('#/training?tab=registry'); await wait();
 const row=d.querySelector('[data-tr="'+tr.id+'"]'); ok(!!row&&row.textContent.includes('Example Hotel & Hall'),'registry displays facility');
 click(row.querySelector('[data-edit-tr]')); await wait();
 ok(d.querySelector('#trFacilityName').value==='Example Hotel & Hall','facility survives editing');
 click(d.querySelector('[data-close]')); await wait();
 await go('#/revenue'); await wait(); click(d.querySelector('[data-add]')); await wait();
 const pick=d.querySelector('#rsPick'); pick.value=tr.id; pick.dispatchEvent(new w.Event('change',{bubbles:true}));
 let exp=d.querySelector('[data-exp-row]'); exp.querySelector('[data-e-amount]').value='1200'; exp.querySelector('[data-e-from]').value='Ruli & Gakenke'; exp.querySelector('[data-e-to]').value='Musanze';
 click(d.querySelector('[data-save]')); await wait(500);
 let rec=S.db().trainingExpenses.find(x=>x.linkedTraining===tr.id);
 ok(!!rec&&rec.expenses[0].routeFrom==='Ruli & Gakenke'&&rec.expenses[0].routeTo==='Musanze','ticket stops saved with expense');
 await go('#/revenue'); await wait(); click(d.querySelector('[data-rev="'+rec.id+'"] td')); await wait();
 const link=[...d.querySelectorAll('a')].find(a=>a.textContent.includes('Suggested road route'));
 ok(!!link&&link.href.includes('origin=Ruli%20%26%20Gakenke')&&link.href.includes('destination=Musanze'),'map directions encode ticket stops');
 ok(d.body.textContent.includes('not a GPS recording'),'route labelled as a suggestion rather than GPS');
 ok(!errors.length,'no boot errors',errors.join(' | ')); done('trainingmaps114');
})().catch(e=>{console.error(e);process.exit(1)});
