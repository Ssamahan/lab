'use strict';
const assert=require('node:assert/strict');
const {createAdminTransport}=require('../assets/js/core/admin-transport.js');
(async()=>{
 const calls=[]; let response;
 const fetch=async(url,opts)=>{calls.push({url,opts});return response;};
 const transport=createAdminTransport({endpoint:'https://example.supabase.co',key:'public',fetch});
 const ok=value=>({ok:true,status:200,json:async()=>value});
 response=ok({data:{samples:[],workingPlans:{}},revision:85,updated_at:'date'});
 const row=await transport.read('token');
 assert.equal(row.revision,85);assert.deepEqual(row.data.samples,[]);
 assert.equal(calls[0].url,'https://example.supabase.co/rest/v1/rpc/lab_admin_read_register');
 assert.equal(calls[0].opts.headers.Authorization,'Bearer token');
 response=ok(86);
 assert.equal(await transport.write('token',85,{samples:[],workingPlans:{}},'device'),86);
 assert.deepEqual(JSON.parse(calls[1].opts.body),{p_expected_revision:85,p_data:{samples:[],workingPlans:{}},p_client_id:'device'});
 response={ok:false,status:409,json:async()=>({code:'40001'})};
 await assert.rejects(transport.write('token',85,{samples:[]},'device'),e=>e.code==='conflict');
 response={ok:false,status:403,json:async()=>({code:'42501'})};
 await assert.rejects(transport.read('token'),e=>e.code==='denied');
 response=ok({data:{},revision:null});await assert.rejects(transport.read('token'),e=>e.code==='invalid_response');
 response=ok(null);await assert.rejects(transport.write('token',85,{},'device'),e=>e.code==='unknown_write');
 response={ok:false,status:408,json:async()=>({})};await assert.rejects(transport.write('token',85,{},'device'),e=>e.code==='unknown_write');
 const count=calls.length;
 await assert.rejects(transport.write('token',null,{},'device'),e=>e.code==='invalid_request');
 await assert.rejects(transport.read(''),e=>e.code==='invalid_request');
 assert.equal(calls.length,count);
 const broken=createAdminTransport({endpoint:'https://example.supabase.co',key:'public',fetch:async()=>{throw Error('offline');}});
 await assert.rejects(broken.write('token',85,{},'device'),e=>e.code==='unknown_write');
 assert.throws(()=>createAdminTransport({endpoint:'http://example.supabase.co',key:'public',fetch}),/configuration/);
 console.log('admin-transport190: authenticated RPC, conflict, denial and uncertain writes verified');
})().catch(e=>{console.error(e);process.exit(1)});
