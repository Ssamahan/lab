/* The manifest sheet: barcodes, footer, signature line, the test list — and the printed copy. */
const {boot,ok,done}=require('./env');
const click=(el)=>el.dispatchEvent(new el.ownerDocument.defaultView.MouseEvent('click',{bubbles:true,cancelable:true}));
const tick=(ms)=>new Promise(r=>setTimeout(r,ms||200));

(async()=>{
  const {w,go}=await boot('#/samples?tab=manifests');
  const doc=w.document, db=()=>w.LS.store.db();

  w.eval(`
    LS.store.commit(d=>{
      const picks=d.samples.slice(0,2);
      picks[0].tests=['Cytology','Gram Stain','Blood Culture']; picks[0].test='Blood Culture';
      picks.forEach(s=>{ s.transporter='Jean Paul NSENGIYUMVA'; s.patientName='Uwase Aline'; });
      d.manifests.unshift({id:'manTest',manifestId:'BC2610260009',type:'Referral',title:'Sample Referral Manifest',
        testingHospital:'CHUK',createdAt:'2026-10-26',samples:picks.map(s=>s.id),status:'Generated',createdBy:'Kelvin SAMAHANI'});
    },{action:'test.seed',entity:'manifest'});
  `);
  await go('#/samples?tab=manifests');
  const card=[...doc.querySelectorAll('[data-man-card]')].find(c=>c.textContent.includes('BC2610260009'));
  click(card.querySelector('[data-man-view]')); await tick(260);
  const sheet=doc.querySelector('#manDoc');
  ok(!!sheet,'the sheet opens');

  /* ── bar codes: the console design, in ink ──────────────────────────── */
  const svgs=[...sheet.querySelectorAll('svg.barcode-svg')];
  ok(svgs.length>=3,'manifest and every sample carry a barcode');
  const rects=[...svgs[0].querySelectorAll('rect')];
  const heights=rects.map(r=>+r.getAttribute('height'));
  const maxH=Math.max(...heights), minH=Math.min(...heights);
  ok(maxH===34,'the tall bars are the console height (34px)');
  ok(Math.abs(minH-23.8)<0.01,'the short bars are seven tenths of it',minH);
  ok(new Set(heights).size===2,'exactly two bar heights, as before');
  ok(rects.map(r=>Math.round((+r.getAttribute('y')+(+r.getAttribute('height')))*10)/10).every(b=>b===maxH),'all bars hang from one baseline');
  ok(rects.length===46,'all forty-six bars are drawn');
  const widths=new Set(rects.map(r=>+r.getAttribute('width')));
  ok(widths.size===2&&[...widths].every(x=>x===1||x===2),'1px and 2px bars, as before');
  const xs=rects.map(r=>+r.getAttribute('x'));
  ok(xs.slice(1).every((x,i)=>x-(xs[i]+(+rects[i].getAttribute('width')))>=1.5),'the bars keep their air');
  ok(sheet.querySelectorAll('div.barcode').length===0,'no CSS-background barcode in the sheet');
  ok(sheet.querySelectorAll('.barcode-lbl').length===0,'and no ID under the bars');

  /* ── the test column is a list, companions first ────────────────────── */
  const rows=[...sheet.querySelectorAll('table')[0].querySelectorAll('tbody tr')];
  const tests=[...rows[0].children[7].querySelectorAll('div')].map(d=>d.textContent.trim());
  ok(tests.join(' · ')==='Cytology · Gram Stain · Blood Culture','the blood culture row lists three tests',tests.join(' | '));

  /* ── footer and signature line ─────────────────────────────────────── */
  const foot=sheet.querySelector('.manifest-foot');
  ok(!!foot&&/text-align:center/.test(foot.getAttribute('style')||''),'the footer is centred');
  ok(/^Specimen Manifest Generated On: /.test(foot.textContent.trim()),'the footer keeps its wording');
  ok(/Samples: 2/.test(foot.textContent)&&/Page 1\/1/.test(foot.textContent),'and its counts');
  const sig=sheet.querySelector('.manifest-sig');
  ok(/flex-wrap:nowrap/.test(sig.getAttribute('style')||''),'the signature line does not wrap');
  ok(/Generated By/.test(sig.textContent)&&/Transported By/.test(sig.textContent)&&/Received By \(at CHUK\)/.test(sig.textContent),'three signatories on one line');
  ok(!/Date of Reception/.test(sheet.textContent),'no reception date');

  /* ── names follow the session ──────────────────────────────────────── */
  ok(/Uwase Aline/.test(sheet.textContent),'the signed-in Admin sees the name');
  w.eval("LS.auth.user={id:'u2',username:'aurelie',name:'Aurelie',role:'Manager'};");
  await go('#/samples?tab=manifests');
  let c=[...doc.querySelectorAll('[data-man-card]')].find(x=>x.textContent.includes('BC2610260009'));
  click(c.querySelector('[data-man-view]')); await tick(240);
  ok(/Uwase Aline/.test(doc.querySelector('#manDoc').textContent),'a signed-in Manager sees the name too');
  click(doc.querySelector('.modal [data-close]')); await tick(200);
  w.eval("LS.auth.user=Object.assign({},LS.auth.VISITOR,{visitor:true});");
  await go('#/samples?tab=manifests');
  c=[...doc.querySelectorAll('[data-man-card]')].find(x=>x.textContent.includes('BC2610260009'));
  click(c.querySelector('[data-man-view]')); await tick(240);
  ok(!/Uwase Aline/.test(doc.querySelector('#manDoc').textContent),'the visitor never sees the name');
  ok(/Confidential/.test(doc.querySelector('#manDoc').textContent),'the visitor sees Confidential');
  click(doc.querySelector('.modal [data-close]')); await tick(220);

  /* ── print: the node on screen, or the page itself ─────────────────── */
  w.eval("LS.auth.user={id:'u1',username:'kelvin',name:'Kelvin SAMAHANI',role:'Admin'};");
  await go('#/samples?tab=manifests');
  c=[...doc.querySelectorAll('[data-man-card]')].find(x=>x.textContent.includes('BC2610260009'));
  click(c.querySelector('[data-man-view]')); await tick(260);
  ok(doc.body.classList.contains('manifest-open'),'the console marks itself while the sheet is open');
  const previewHTML=doc.querySelector('#manDoc').outerHTML;
  w.eval("window.__printed=null; LSU.print=function(html){ window.__printed=html; };");
  click(doc.querySelector('[data-print-man]')); await tick(160);
  const printed=w.eval('window.__printed');
  ok(!!printed,'Print / PDF hands a document to the printer');
  ok(!!printed&&printed.indexOf(previewHTML)>=0,'and that document is the sheet on screen, node for node');
  ok(/<svg class="barcode-svg"/.test(printed),'with the bars as ink');
  ok(/\.manifest-foot\{position:fixed/.test(printed)&&/text-align:center/.test(printed),'the printed footer is fixed and centred');
  ok(/Cytology/.test(printed)&&/Gram Stain/.test(printed),'the printed list carries the routine tests');
  ok(/Uwase Aline/.test(printed),'the printed sheet carries the name for a signed-in user');
  click(doc.querySelector('.modal [data-close]')); await tick(260);
  ok(!doc.body.classList.contains('manifest-open'),'and releases the print mode when the sheet closes');

  done('sheet');
})().catch(e=>{console.error(e);process.exit(1);});
